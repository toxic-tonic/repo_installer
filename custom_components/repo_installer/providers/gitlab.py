"""GitLab (gitlab.com and self-hosted, API v4)."""

from __future__ import annotations

from typing import Any
from urllib.parse import quote

from yarl import URL

from ..const import PROVIDER_GITLAB
from ..version import is_prerelease
from .base import (
    Origin,
    Provider,
    Release,
    RepoNotFoundError,
    SchemaMismatchError,
    ZipAsset,
    origin,
    release_version,
)

GITLAB_HOST = "gitlab.com"

# gitlab.com serves release links (…/-/releases/<tag>/downloads/…) and the
# generic package registry itself (checked live 2026-10, gitlab-org/cli).
GITLAB_COM_ASSET_HOSTS = ("gitlab.com",)


class GitLabProvider(Provider):
    key = PROVIDER_GITLAB
    name = "GitLab"

    @property
    def _is_dotcom(self) -> bool:
        return (self.location.base_url.host or "").lower() == GITLAB_HOST

    @property
    def repo_api_url(self) -> URL:
        # The project path is one URL-encoded segment: group%2Fsub%2Fproject
        base = str(self.location.base_url).rstrip("/")
        return URL(f"{base}/api/v4/projects/{quote(self.location.path, safe='')}", encoded=True)

    _project_id: int | None = None  # known after async_probe()

    def _auth_headers(self) -> dict[str, str]:
        return {"PRIVATE-TOKEN": self._token}

    @property
    def download_origins(self) -> frozenset[Origin]:
        if self._is_dotcom:
            return frozenset(("https", host, 443) for host in GITLAB_COM_ASSET_HOSTS)
        return frozenset({origin(self.location.base_url)})

    def _validate_repo(self, data: Any) -> None:
        if not (
            isinstance(data, dict)
            and isinstance(data.get("id"), int)
            and str(data.get("path_with_namespace", "")).lower() == self.location.path.lower()
        ):
            raise SchemaMismatchError("not a GitLab project answer")
        self._project_id = data["id"]

    async def async_get_latest_release(self, include_prereleases: bool) -> Release:
        if self._project_id is None:
            await self.async_probe()  # numeric id, for package links using it
        # Newest first (released_at). GitLab has no pre-release flag: a release
        # counts as pre-release if its version has a pre-release part (1.0.0-rc.1).
        releases = await self._get_json(
            URL(f"{self.repo_api_url}/releases", encoded=True), {"per_page": "20"}
        )
        for data in releases or []:
            if data.get("upcoming_release"):
                continue
            pre = is_prerelease(release_version(data.get("name"), data.get("tag_name") or ""))
            if pre and not include_prereleases:
                continue
            links = (data.get("assets") or {}).get("links") or []
            return self._build_release(
                tag=data.get("tag_name") or "",
                name=data.get("name"),
                body=data.get("description"),
                html_url=(data.get("_links") or {}).get("self"),
                prerelease=pre,
                # Assets are links, not uploaded files; uploaded source archives
                # (assets.sources) are generated by GitLab and never used.
                zips=[
                    ZipAsset(link.get("name", ""), link.get("direct_asset_url") or link.get("url", ""))
                    for link in links
                    if link.get("name", "").lower().endswith(".zip")
                    or link.get("url", "").lower().endswith(".zip")
                ],
            )
        raise RepoNotFoundError("no releases")

    def is_own_asset_url(self, url: str | URL) -> bool:
        url = URL(url)
        base = self.location.base_url
        if origin(url) != origin(base):
            return False
        root = base.path.rstrip("/")
        path = url.raw_path.lower()
        allowed = [
            # release link (direct_asset_url), uploads
            f"{root}/{self.location.path}/".lower(),
            # generic package registry of this project, by path or numeric id
            f"{root}/api/v4/projects/{quote(self.location.path, safe='')}/packages/".lower(),
        ]
        if self._project_id is not None:
            allowed.append(f"{root}/api/v4/projects/{self._project_id}/packages/")
        return path.startswith(tuple(allowed))
